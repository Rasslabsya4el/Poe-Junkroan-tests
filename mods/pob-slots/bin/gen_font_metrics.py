"""Writes hooks/fontmetrics.ts: per-character advance widths (em x 1000) of Segoe UI regular and semibold, measured with PIL from C:/Windows/Fonts."""
import json
import sys
from pathlib import Path
from PIL import ImageFont

FONTS = Path('C:/Windows/Fonts')
CHARS = ''.join(chr(c) for c in range(32, 127)) + 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя' + '…·–—№«»≈→←↑↓×±°’‘“”'
SIZE = 2000


def widths(file: str) -> list[int]:
    f = ImageFont.truetype(str(FONTS / file), SIZE)
    return [round(f.getlength(ch) / SIZE * 1000) for ch in CHARS]


def main(out: str) -> None:
    reg, sb = widths('segoeui.ttf'), widths('seguisb.ttf')
    arr = lambda a: '[' + ','.join(map(str, a)) + ']'
    text = ("// GENERATED by bin/gen_font_metrics.py (PIL getlength of segoeui.ttf / seguisb.ttf at 2000 px): the advance of each character in 1/1000 em. Do not edit by hand.\n"
            f"export const EM_CHARS = {json.dumps(CHARS, ensure_ascii=False)}\n" +
            f"export const EM_REG = {arr(reg)}\nexport const EM_SB = {arr(sb)}\n")
    with open(out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path(__file__).resolve().parent.parent / 'hooks' / 'fontmetrics.ts'))
