@pytest.mark.pob
@needs_pob
def test_the_export_is_not_byte_stable_under_a_reload(runtime) -> None:
    """Why the comparisons above are canonical, not byte-for-byte: PoB's own export changes
    bytes when the build is merely reloaded from it, while the canonical form does not."""

    runtime.load_reopen_source(_fixture_xml(SAMPLE_FIXTURES[0]))
    first = runtime.export_build_xml()
    runtime.load_reopen_source(first)
    second = runtime.export_build_xml()
    assert first != second, "the export became byte-stable: tighten these tests to byte equality"
    assert canonical_xml(first) == canonical_xml(second)


