@pytest.mark.pob
@needs_pob
def test_inplace_skill_write_is_several_times_faster(runtime) -> None:
    base_xml = _fixture_xml(SAMPLE_FIXTURES[0])
    payload = SKILL_PAYLOADS["support_swap"]
    runtime.load_reopen_source(base_xml)
    runtime.apply_skill_state(payload)  # warm

    def timed(fn) -> float:
        best = float("inf")
        for _ in range(3):
            runtime.load_reopen_source(base_xml)
            start = time.perf_counter()
            fn(payload)
            best = min(best, time.perf_counter() - start)
        return best

    reference = timed(runtime._apply_skill_state_xml)
    inplace = timed(runtime.apply_skill_state)
    assert inplace * 3 < reference, f"in-place {inplace*1000:.0f} ms vs reload {reference*1000:.0f} ms"


