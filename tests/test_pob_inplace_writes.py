_ID_LIST = re.compile(r"-?\d+(?:,-?\d+)*")
_MASTERY_LIST = re.compile(r"\{-?\d+,-?\d+\}(?:,\{-?\d+,-?\d+\})*")
_MASTERY_PAIR = re.compile(r"\{(-?\d+),(-?\d+)\}")
# PoB's own Save walks Lua hash tables with pairs(): the order of the Spec's `nodes` ids, of the
# <Input>/<Placeholder> elements and of the attributes inside an element is a property of the Lua
# table's layout, not of the build. A plain load -> export -> load -> export round trip already
# shuffles all three (test_the_export_is_not_byte_stable_under_a_reload), so byte equality would
# fail for the reference path against itself. Everything that carries meaning - element order in
# Skills / Items / Spec, every attribute value, the set of allocated nodes - is compared exactly.
_UNORDERED_CHILDREN = {"ConfigSet", "Config"}


def _canonical_attr(name: str, value: str) -> str:
    if name == "nodes" and _ID_LIST.fullmatch(value):
        return ",".join(sorted(value.split(","), key=int))
    if name == "masteryEffects" and _MASTERY_LIST.fullmatch(value):
        pairs = sorted((int(a), int(b)) for a, b in _MASTERY_PAIR.findall(value))
        return ",".join(f"{{{a},{b}}}" for a, b in pairs)
    return value


def _canonical_element(elem: ElementTree.Element) -> tuple:
    text = (elem.text or "").strip()
    if elem.tag == "URL":
        text = ""  # the tree URL is the `nodes` list in its pairs() order, nothing more
    children = [_canonical_element(child) for child in elem]
    if elem.tag in _UNORDERED_CHILDREN:
        children.sort()
    if elem.tag == "SkillSet":
        # socket groups carrying a `source` are generated by the calc from allocated nodes and
        # items (CalcSetup.lua:1364), appended in the pairs() order of allocNodes; the authored
        # groups - the ones the payload writes and mainSocketGroup indexes - keep their order
        authored = [child for child in children if "source" not in dict(child[1])]
        generated = sorted(child for child in children if "source" in dict(child[1]))
        children = authored + generated
    return (elem.tag, tuple(sorted((k, _canonical_attr(k, v)) for k, v in elem.attrib.items())), text, tuple(children))


def canonical_xml(xml_text: str) -> tuple:
    return _canonical_element(ElementTree.fromstring(xml_text))


