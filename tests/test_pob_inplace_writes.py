# --- tree mutation --------------------------------------------------------------------


def _tree_light(live: worker.HeadlessLuaRuntime) -> dict[str, Any]:
    return live.read_tree_light({})


def _mutation_sequence(live: worker.HeadlessLuaRuntime, base_xml: str, *, always_rebuild: bool) -> list[Any]:
    """Adds, a removal that cascades, a mastery add and a mastery removal, in one order."""

    live.load_reopen_source(base_xml)
    # plain allocated nodes only: a Mastery needs its effect id on the way back in, and a Socket
    # carries a jewel, neither of which this sequence is about
    allocated = json.loads(
        live._bridge.execute(
            "\n".join(
                (
                    "local json = require('dkjson')",
                    "local spec = build.spec",
                    "local out = {}",
                    "for id, node in pairs(spec.allocNodes) do",
                    "  if node.type == 'Normal' and not node.ascendancyName then table.insert(out, id) end",
                    "end",
                    "table.sort(out)",
                    "return json.encode(out)",
                )
            ),
            nret=1,
        )[0]
    )
    mastery = json.loads(
        live._bridge.execute(
            "\n".join(
                (
                    "local json = require('dkjson')",
                    "local spec = build.spec",
                    "local out, effect = nil, nil",
                    "for id, node in pairs(spec.nodes) do",
                    "  if node.type == 'Mastery' and not node.alloc and node.path and #node.path <= 3 and not out then",
                    "    for _, eff in ipairs(node.masteryEffects or {}) do effect = eff.effect break end",
                    "    if effect then out = id end",
                    "  end",
                    "end",
                    "return json.encode({ node = out, effect = effect })",
                )
            ),
            nret=1,
        )[0]
    )
    # a node whose removal cascades: the deepest allocated node's neighbour chain
    trunk = allocated[len(allocated) // 3]
    leaf = allocated[-1]
    steps: list[dict[str, Any]] = [
        {"add_node_ids": [], "remove_node_ids": [leaf], "mastery_effects": {}},
        {"add_node_ids": [leaf], "remove_node_ids": [], "mastery_effects": {}},
        {"add_node_ids": [], "remove_node_ids": [trunk], "mastery_effects": {}},   # cascade
        {"add_node_ids": [trunk, leaf], "remove_node_ids": [], "mastery_effects": {}},
        {"add_node_ids": [], "remove_node_ids": [], "mastery_effects": {}},        # no-op
    ]
    if mastery.get("node") and mastery.get("effect"):
        steps.append({"add_node_ids": [mastery["node"]], "remove_node_ids": [],
                      "mastery_effects": {str(mastery["node"]): int(mastery["effect"])}})
        steps.append({"add_node_ids": [], "remove_node_ids": [mastery["node"]], "mastery_effects": {}})
    out: list[Any] = []
    for step in steps:
        out.append(live.mutate_tree_nodes(step, always_rebuild_paths=always_rebuild))
        out.append(_tree_light(live))
    out.append(canonical_xml(live.export_build_xml()))
    out.append(_stats(live))
    return out


@pytest.mark.pob
@needs_pob
@pytest.mark.parametrize("fixture_name", SAMPLE_FIXTURES)
def test_mutate_tree_nodes_without_the_extra_path_rebuild(runtime, fixture_name: str) -> None:
    base_xml = _fixture_xml(fixture_name)
    reference = _mutation_sequence(runtime, base_xml, always_rebuild=True)
    observed = _mutation_sequence(runtime, base_xml, always_rebuild=False)
    assert observed == reference
