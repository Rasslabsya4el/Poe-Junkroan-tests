"""Issue #1119 unit 3 fix: the day-1 readers take PoB's real Lua shapes, not dict fakes.

Each snippet below is the head of a real PoB data file (src/Data/ModMaster.lua, ModExplicit.lua, ModFlask.lua,
Bases/flask.lua), parsed by the real `parse_lua_return_value` / `parse_lua_assignment_table`. No PoB session.
ModMaster.lua is an unkeyed list of bench rows (PoB has no mod id there), so the parser returns a Python list.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "src"))

import day1_lines  # noqa: E402
from day1_lines import _mod_records  # noqa: E402
from junkroan.optimizer import flask_lines  # noqa: E402
from junkroan.optimizer.rails import BenchRails, GearRails, Rails, WishlistRails  # noqa: E402

MODMASTER_HEAD = """-- This file is automatically generated, do not edit!
-- Item data (c) Grinding Gear Games

return {
	{ type = "Prefix", affix = "Upgraded", modTags = { "resource", "life" }, "+(15-25) to maximum Life", statOrder = { 1594 }, level = 15, group = "IncreasedLife", types = { ["Body Armour"] = true, ["Gloves"] = true, }, },
	{ type = "Suffix", affix = "of Craft", modTags = { "elemental", "fire", "resistance" }, "+(16-20)% to Fire Resistance", statOrder = { 1651 }, level = 15, group = "FireResistance", types = { ["Body Armour"] = true, ["Gloves"] = true, }, },
}
"""

MODEXPLICIT_HEAD = """-- This file is automatically generated, do not edit!
return {
	["Strength1"] = { type = "Suffix", affix = "of the Brute", "+(8-12) to Strength", statOrder = { 1203 }, level = 1, group = "Strength", weightKey = { "ring", "default", }, weightVal = { 1000, 0, }, },
}
"""

FLASK_BASES_HEAD = """itemBases = {}
itemBases["Divine Life Flask"] = { type = "Flask", tags = { life_flask = true, default = true }, req = { level = 1 }, }
"""

MODFLASK_HEAD = """return {
	["FlaskIncreasedRecoverySpeed1"] = { type = "Prefix", affix = "Undiluted", "(41-46)% increased Recovery rate", statOrder = { 879 }, level = 1, group = "FlaskIncreasedRecoverySpeed", weightKey = { "life_flask", "default", }, weightVal = { 1000, 0, }, },
}
"""


def _rails() -> Rails:
    return Rails(gear=GearRails(wishlist=WishlistRails(item_level={"default": 72}), bench=BenchRails(max_map_tier=10)))


def _write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def test_mod_records_reads_the_real_modmaster_list_shape(tmp_path, monkeypatch):
    _write(tmp_path, "src/Data/ModExplicit.lua", MODEXPLICIT_HEAD)
    _write(tmp_path, "src/Data/ModMaster.lua", MODMASTER_HEAD)
    monkeypatch.setattr(day1_lines, "flask_bases", lambda *args, **kwargs: ())

    explicit, bench, flasks = _mod_records(_rails(), tmp_path)

    assert [(r["id"], r["type"], r["level"], r["template"]) for r in explicit] == [
        ("Strength1", "Suffix", 1, ["+(8-12) to Strength"]),
    ]
    # PoB's bench rows have no mod id: each is labelled by its 1-based position in ModMaster.lua
    assert [(r["id"], r["type"], r["level"], r["template"]) for r in bench] == [
        ("ModMaster#1", "Prefix", 15, ["+(15-25) to maximum Life"]),
        ("ModMaster#2", "Suffix", 15, ["+(16-20)% to Fire Resistance"]),
    ]
    assert all("unlock" in r for r in bench)
    assert flasks == []


def test_flask_readers_take_the_real_keyed_shapes(tmp_path):
    _write(tmp_path, "src/Data/Bases/flask.lua", FLASK_BASES_HEAD)
    _write(tmp_path, "src/Data/Bases/tincture.lua", "itemBases = {}\n")
    _write(tmp_path, "src/Data/ModFlask.lua", MODFLASK_HEAD)

    bases = flask_lines.flask_bases(10, tmp_path)
    assert [(b.name, b.kind, b.drop_level) for b in bases] == [("Divine Life Flask", "life", 1)]

    mods = flask_lines.flask_mods(bases[0], 72, tmp_path)
    assert [m.id for m in mods] == ["FlaskIncreasedRecoverySpeed1"]
